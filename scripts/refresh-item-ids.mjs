import {writeFile} from 'node:fs/promises';
const revision=process.argv[2]??'ac79ed8bd8926bec7bf172aa291574b4d944b0e7';
if(!/^[a-f0-9]{40}$/.test(revision))throw new Error('Provide a full RuneLite commit SHA.');
const url=`https://raw.githubusercontent.com/runelite/runelite/${revision}/runelite-api/src/main/java/net/runelite/api/gameval/ItemID.java`;
const response=await fetch(url);if(!response.ok)throw new Error(`RuneLite returned ${response.status}`);
const source=await response.text(),names={};
const labels=[];
for(const match of source.matchAll(/^\t\/\*\*\r?\n\t \* ([^\r\n]+)\r?\n\t \*\/\r?\n\tpublic static final int [A-Z][A-Z0-9_]* = (\d+);/gm))labels[Number(match[2])]=match[1];
// Only top-level inventory constants; exclude nested certificate IDs.
for(const match of source.matchAll(/^\tpublic static final int ([A-Z][A-Z0-9_]*) = (\d+);/gm))names[match[2]]=match[1];
if(!names[27352])throw new Error('Unrecognized ItemID source.');
await writeFile(new URL('../src/core/item-ids.mjs',import.meta.url),`// Generated by scripts/refresh-item-ids.mjs from ${url}\nexport const ITEM_NAMES=${JSON.stringify(names)};\n`);
await writeFile(new URL('../src/core/item-labels.mjs',import.meta.url),`// Generated from ${url}\nexport const ITEM_LABELS=${JSON.stringify(labels)};\n`);
